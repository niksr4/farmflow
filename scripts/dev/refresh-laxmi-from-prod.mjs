/**
 * Rebuild Laxmi in dev from production, so the muster cutover can be rehearsed end to end before
 * it is done to the real tenant.
 *
 * Run: node --env-file=.env.local scripts/dev/refresh-laxmi-from-prod.mjs            (dry run)
 *      node --env-file=.env.local scripts/dev/refresh-laxmi-from-prod.mjs --commit
 *
 * Needs PROD_URL exported (prod's DATABASE_URL, from .env.vercel.production). Production is only
 * ever read here -- every write in this file targets DATABASE_URL_DEV, and there is an assertion
 * below that refuses to run if those two happen to be the same string.
 *
 * WHY THIS EXISTS. Laxmi is about to be moved from the old labour workflow to the muster, and that
 * is a one-way change to a real customer's books. Rehearsing it on Estate Mock proves the mechanics
 * but not the outcome, because the outcome depends on Laxmi's own data: 237 labour transactions,
 * 23 workers, 670 attendance records already marked, and 6 locations. What we need to see before
 * the call is what *their* numbers look like on the other side of the cutover.
 *
 * WHAT IS DELIBERATELY NOT COPIED. Audit logs, security events, error events, dormancy probes,
 * digest feedback, weekly metrics and agent findings. None of them are visible in the walkthrough,
 * and security_events in particular is a login trail belonging to a real person. A rehearsal copy
 * should carry the estate's operational data and none of its surveillance.
 *
 * THE PASSWORD IS NOT COPIED EITHER. The dev row gets a known rehearsal password set here. Copying
 * the real hash would put a live credential in a database with weaker access rules, to no benefit
 * -- nobody needs the dev copy to accept the production password.
 *
 * PRE-CUTOVER STATE IS PART OF THE COPY. Production Laxmi has no `tenant_labour_entry_mode` row and
 * no `labour_assignments`; dev may have leftovers from earlier testing. Those are cleared, because
 * a rehearsal that starts half-cut-over rehearses nothing.
 */
import { neon } from "@neondatabase/serverless"
import { hashPassword } from "../../lib/passwords.ts"

const LAXMI = "0905ea0c-46dc-42be-8a72-e0b29c10cbea"
const REHEARSAL_PASSWORD = "laxmi-rehearsal"

const commit = process.argv.includes("--commit")

if (!process.env.PROD_URL) {
  console.error("PROD_URL is not set. Export prod's DATABASE_URL from .env.vercel.production first.")
  process.exit(1)
}
if (!process.env.DATABASE_URL_DEV) {
  console.error("DATABASE_URL_DEV is not set. Run with --env-file=.env.local.")
  process.exit(1)
}
// The whole safety story of this script is "prod is read-only". That holds only if the two
// connection strings are actually different databases.
if (process.env.PROD_URL === process.env.DATABASE_URL_DEV) {
  console.error("PROD_URL and DATABASE_URL_DEV are the same database. Refusing to run.")
  process.exit(1)
}

const prod = neon(process.env.PROD_URL)
const dev = neon(process.env.DATABASE_URL_DEV)

/**
 * Copy order is FK order, and it is load-bearing rather than tidy:
 *   locations          <- nearly everything points here
 *   account_activities <- labour and expense rows carry a composite FK on (tenant_id, code)
 *   users              <- transaction_history.user_uuid points here
 *   attendance_workers <- attendance_records.worker_id points here
 * Deletion runs in exact reverse.
 */
const TABLES = [
  "locations",
  "account_activities",
  "users",
  "attendance_workers",
  "attendance_records",
  "labor_transactions",
  "expense_transactions",
  "current_inventory",
  "transaction_history",
  "rainfall_records",
  "tenant_modules",
  "user_modules",
]

/**
 * Integer primary keys are generated by dev's own sequence rather than carried over. Preserving
 * them would mean inserting explicit ids into a sequence shared with every other dev tenant, which
 * either collides now or makes the *next* insert collide. Nothing outside this copy set references
 * these ids for Laxmi (expense_inventory_links is empty for them), so re-numbering costs nothing.
 * UUID keys are carried across unchanged -- they are unique by construction and several tables
 * point at them.
 */
const REGENERATE_ID = new Set([
  "labor_transactions",
  "expense_transactions",
  "transaction_history",
  "rainfall_records",
  "user_modules",
])

const columnsOf = async (client, table) => {
  const rows = await client`
    SELECT column_name, data_type FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = ${table}
    ORDER BY ordinal_position`
  return rows.map((r) => r.column_name)
}

/** column name -> data_type, per table on dev. Needed for the json encoding below. */
const typesOf = async (client, table) => {
  const rows = await client`
    SELECT column_name, data_type FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = ${table}`
  return Object.fromEntries(rows.map((r) => [r.column_name, r.data_type]))
}

/**
 * A json/jsonb column comes back from the driver already parsed into a JS object, and handing that
 * object straight back as a bind parameter gets it encoded a second time -- Postgres then receives
 * a quoted string where it expects an object and rejects it with "invalid input syntax for type
 * json", naming a parameter number and nothing else. Encoding once, here, is the fix.
 *
 * `labor_transactions` carries this: {"laborCount":11,"costPerLabor":450}. It is exactly the sort
 * of column a copy script forgets, because eleven of the twelve tables have none.
 */
const encode = (value, dataType) => {
  if (value == null) return null
  if (dataType === "json" || dataType === "jsonb") {
    return typeof value === "string" ? value : JSON.stringify(value)
  }
  return value
}

const chunk = (rows, size) => {
  const out = []
  for (let i = 0; i < rows.length; i += size) out.push(rows.slice(i, i + size))
  return out
}

console.log(`\n=== Laxmi: production -> dev ${commit ? "(WRITING)" : "(dry run)"} ===\n`)

const [prodTenant] = await prod`SELECT id, name FROM tenants WHERE id = ${LAXMI}`
if (!prodTenant) {
  console.error("Laxmi not found in production.")
  process.exit(1)
}

const plan = []
for (const table of TABLES) {
  const [pCols, dCols] = await Promise.all([columnsOf(prod, table), columnsOf(dev, table)])
  if (!dCols.length) {
    console.log(`  ${table.padEnd(24)} SKIP -- table does not exist on dev`)
    continue
  }
  // Dev runs ahead of prod, so it has columns prod has never heard of. Copy the intersection and
  // say so, rather than building an INSERT naming a column the source cannot supply.
  const shared = pCols.filter((c) => dCols.includes(c))
  const devOnly = dCols.filter((c) => !pCols.includes(c))
  const cols = REGENERATE_ID.has(table) ? shared.filter((c) => c !== "id") : shared

  const rows = await prod.query(`SELECT ${cols.map((c) => `"${c}"`).join(", ")} FROM "${table}" WHERE tenant_id = $1`, [LAXMI])
  const [{ n: devHas }] = await dev.query(`SELECT COUNT(*)::int n FROM "${table}" WHERE tenant_id = $1`, [LAXMI])

  plan.push({ table, cols, rows, types: await typesOf(dev, table) })
  const note = devOnly.length ? `  (dev-only cols left at default: ${devOnly.join(", ")})` : ""
  console.log(`  ${table.padEnd(24)} prod ${String(rows.length).padStart(5)} -> dev has ${String(devHas).padStart(5)}${note}`)
}

const [{ n: staleAssignments }] = await dev`SELECT COUNT(*)::int n FROM labour_assignments WHERE tenant_id = ${LAXMI}`
const staleMode = await dev`SELECT assignments_from FROM tenant_labour_entry_mode WHERE tenant_id = ${LAXMI}`
console.log(`\n  pre-cutover state to clear: ${staleAssignments} labour_assignments, entry mode = ${staleMode[0]?.assignments_from ?? "none"}`)

if (!commit) {
  console.log("\nDry run. Re-run with --commit to write.\n")
  process.exit(0)
}

/**
 * CLEARING IS NOT THE REVERSE OF COPYING, and assuming it was is the bug this replaces.
 *
 * The copy set is twelve tables. What *points at* those twelve is much wider: dev Laxmi has 817
 * security_events referencing their user, plus audit_logs, worker_ledger, biometric_punches,
 * user_locations and the token tables. Deleting `users` in reverse copy order therefore fails on a
 * foreign key from a table this script never mentions -- and it would have failed tonight, not in
 * some hypothetical future, because those 817 rows exist right now.
 *
 * So the clear is discovered rather than listed:
 *   1. children that have no tenant_id of their own are deleted via their parent
 *      (`WHERE user_id IN (SELECT id FROM users WHERE tenant_id = ...)`),
 *   2. then every table with a tenant_id column, retried in passes.
 *
 * The retry loop is doing real work, not defending against nothing: a fixed order would have to be
 * maintained by hand every time a table is added, which is the same maintenance burden that let
 * this go wrong in the first place. Passes stop as soon as one completes with no failures, and the
 * script gives up loudly rather than looping forever.
 */
const tenantTables = (await dev`
  SELECT c.table_name FROM information_schema.columns c
  JOIN information_schema.tables t ON t.table_name = c.table_name AND t.table_schema = c.table_schema
  WHERE c.table_schema = 'public' AND c.column_name = 'tenant_id' AND t.table_type = 'BASE TABLE'
  ORDER BY 1`).map((r) => r.table_name)

const orphanChildren = await dev`
  SELECT tc.table_name AS child, kcu.column_name AS fk_col, ccu.table_name AS parent
  FROM information_schema.table_constraints tc
  JOIN information_schema.key_column_usage kcu ON tc.constraint_name = kcu.constraint_name
  JOIN information_schema.constraint_column_usage ccu ON tc.constraint_name = ccu.constraint_name
  WHERE tc.constraint_type = 'FOREIGN KEY'
    AND tc.table_schema = 'public'
    AND ccu.table_name = ANY(${tenantTables})
    AND tc.table_name <> ccu.table_name
    AND NOT EXISTS (
      SELECT 1 FROM information_schema.columns c2
      WHERE c2.table_schema = 'public' AND c2.table_name = tc.table_name AND c2.column_name = 'tenant_id'
    )`

for (const { child, fk_col, parent } of orphanChildren) {
  const gone = await dev.query(
    `DELETE FROM "${child}" WHERE "${fk_col}" IN (SELECT id FROM "${parent}" WHERE tenant_id = $1) RETURNING 1`,
    [LAXMI],
  )
  if (gone.length) console.log(`  cleared ${String(gone.length).padStart(5)} ${child} (via ${parent})`)
}

let remaining = [...tenantTables]
for (let pass = 1; pass <= 6 && remaining.length; pass += 1) {
  const failed = []
  for (const table of remaining) {
    try {
      await dev.query(`DELETE FROM "${table}" WHERE tenant_id = $1`, [LAXMI])
    } catch (error) {
      failed.push(table)
      if (pass === 6) console.error(`  ${table}: ${error.message}`)
    }
  }
  if (!failed.length) { remaining = []; break }
  if (failed.length === remaining.length) {
    console.error(`\nStuck clearing: ${failed.join(", ")}. Nothing has been re-inserted; dev Laxmi is partially cleared.`)
    process.exit(1)
  }
  remaining = failed
}
if (remaining.length) {
  // Falling out of the loop still holding tables means the passes ran out, not that the work
  // finished. Copying on top of a half-cleared tenant would duplicate rows silently.
  console.error(`\nCould not clear after 6 passes: ${remaining.join(", ")}. Nothing re-inserted.`)
  process.exit(1)
}
console.log("\ncleared dev Laxmi")

await dev`INSERT INTO tenants (id, name) VALUES (${LAXMI}, ${prodTenant.name})
          ON CONFLICT (id) DO UPDATE SET name = EXCLUDED.name`

/**
 * TRIGGERS ARE OFF FOR THE COPY, and this is not a convenience.
 *
 * `transaction_history` carries `update_inventory()`, which upserts the derived row in
 * `current_inventory`. This script copies *both* tables verbatim from production, so letting the
 * trigger fire would apply every historical movement a second time on top of the already-correct
 * balance -- a dev copy that quietly disagreed with production about how much fertiliser is in the
 * shed, which is precisely the number the walkthrough is about.
 *
 * (Running it also fails outright: the trigger's `ON CONFLICT (item_type, tenant_id, location_id)`
 * matches no index that Postgres can infer, because both candidate unique indexes are partial and
 * the statement has no WHERE clause to pair with them. That is true on production too -- same
 * indexes, verified -- so it is a real defect rather than a dev artifact. It is not this script's
 * problem to fix, but it is written down here because this is where it surfaced.)
 */
const triggerTables = plan.filter((p) => p.rows.length).map((p) => p.table)
for (const table of triggerTables) await dev.query(`ALTER TABLE "${table}" DISABLE TRIGGER USER`)

try {
for (const { table, cols, rows, types } of plan) {
  if (!rows.length) continue
  for (const batch of chunk(rows, 200)) {
    const params = []
    const tuples = batch.map((row) => {
      const slots = cols.map((c) => {
        params.push(encode(row[c], types[c]))
        return `$${params.length}`
      })
      return `(${slots.join(", ")})`
    })
    await dev.query(
      `INSERT INTO "${table}" (${cols.map((c) => `"${c}"`).join(", ")}) VALUES ${tuples.join(", ")}`,
      params,
    )
  }
  console.log(`  copied ${String(rows.length).padStart(5)} -> ${table}`)
}
} finally {
  // In a finally, because leaving dev with triggers disabled is a far worse state than a failed
  // copy: nothing would complain, and inventory would silently stop updating for every tenant.
  for (const table of triggerTables) await dev.query(`ALTER TABLE "${table}" ENABLE TRIGGER USER`)
}

const [user] = await dev`SELECT id, username FROM users WHERE tenant_id = ${LAXMI} ORDER BY created_at LIMIT 1`
await dev`UPDATE users SET password_hash = ${hashPassword(REHEARSAL_PASSWORD)} WHERE tenant_id = ${LAXMI}`

console.log("\n=== done ===")
console.log(`  login: ${user?.username}  /  ${REHEARSAL_PASSWORD}`)
console.log("  at:    http://localhost:3000\n")

const after = await dev`SELECT
  (SELECT COUNT(*) FROM locations           WHERE tenant_id = ${LAXMI})::int locations,
  (SELECT COUNT(*) FROM attendance_workers  WHERE tenant_id = ${LAXMI})::int workers,
  (SELECT COUNT(*) FROM attendance_records  WHERE tenant_id = ${LAXMI})::int attendance,
  (SELECT COUNT(*) FROM labor_transactions  WHERE tenant_id = ${LAXMI})::int labour,
  (SELECT COUNT(*) FROM account_activities  WHERE tenant_id = ${LAXMI})::int codes,
  (SELECT COUNT(*) FROM labour_assignments  WHERE tenant_id = ${LAXMI})::int assignments`
console.log(" ", after[0])
