/**
 * Integer primary keys are regenerated by dev's own sequence. Preserving them means inserting
 * explicit ids into a sequence shared with every other dev tenant, which either collides now or
 * makes the next insert collide. UUID keys are carried across unchanged -- unique by construction,
 * and several tables point at them.
 */
const REGENERATE_ID = new Set([
  "app_error_events", "curing_records", "dispatch_records", "expense_inventory_links",
  "expense_transactions", "labor_transactions", "other_sales_records", "pepper_records",
  "processing_records", "push_subscriptions", "quality_grading_records", "rainfall_records",
  "receivables", "sales_records", "transaction_history", "user_locations", "user_modules",
])

/**
 * Columns whose VALUES are personal data. Matched by name against the live schema rather than
 * listed, so a new one is covered the day it is added.
 *
 * `email` is included: a dev copy that holds a real owner's address is one misconfigured
 * RESEND_API_KEY away from emailing them a test digest.
 */
const PII_NAME = /(bank_account|bank_ifsc|bank_name|ifsc|aadhaar|aadhar|^pan$|_pan$|phone|mobile|email|address|upi|token_hash|ip_address)/i

/** Only text-ish columns are masked. The pattern also matches `email_verified_at` (a timestamp) and
 *  `password_reset_required` (a boolean), and writing a string into either would fail the insert. */
const MASKABLE_TYPES = new Set(["text", "character varying", "character"])

/** Password hashes are replaced, never copied: a live credential in a weaker database buys nothing. */
const CREDENTIAL_NAME = /password_hash/i

/**
 * ⚠ GENERATED COLUMNS ARE EXCLUDED, OR THE INSERT IS REFUSED OUTRIGHT.
 *
 * `labour_assignments.total_cost` (scripts/116) and `picking_records.total_cost` (scripts/154) are
 * `GENERATED ALWAYS AS (...) STORED`, for the reason 116 gives: "so the total can never drift from
 * its parts". Postgres rejects any explicit value with 428C9, "cannot insert a non-DEFAULT value
 * into column". Hit on the first real run of this script, at attendance_records -> labour_assignments.
 *
 * refresh-laxmi-from-prod.mjs never met this because it copied Laxmi PRE-cutover, when
 * labour_assignments was empty for them -- so the one table with a generated column carried no rows.
 * Dropping them is also correct rather than merely necessary: the column recomputes from the parts
 * on insert, so the copy gets the same figure without being told it.
 */
const columnsOf = async (client, table) =>
  rows(
    await client.query(
      `SELECT column_name, data_type FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = $1
          AND is_generated <> 'ALWAYS'
          AND identity_generation IS DISTINCT FROM 'ALWAYS'
        ORDER BY ordinal_position`,
      [table],
    ),
  )

const tenantTablesOf = async (client) =>
  rows(
    await client.query(
      `SELECT c.table_name FROM information_schema.columns c
         JOIN information_schema.tables t
           ON t.table_schema = c.table_schema AND t.table_name = c.table_name
        WHERE c.table_schema = 'public' AND c.column_name = 'tenant_id'
          AND t.table_type = 'BASE TABLE'
        ORDER BY c.table_name`,
    ),
  ).map((r) => r.table_name)

/**
 * A json/jsonb column comes back from the driver already parsed, and handing that object back as a
 * bind parameter encodes it twice -- Postgres then gets a quoted string where it expects an object
 * and rejects it with "invalid input syntax for type json", naming a parameter number and nothing
 * else. `labor_transactions.labor_entries` carries this, and it is exactly the column a copy script
 * forgets because the other thirty-five have none.
 */
const encode = (value, dataType) => {
  if (value == null) return null
  if (dataType === "json" || dataType === "jsonb") {
    return typeof value === "string" ? value : JSON.stringify(value)
  }
  return value
}

/**
 * Deterministic, so a second run produces the same dev database and two rows that differed in prod
 * still differ here. Shape-preserving enough to exercise validation: a masked IFSC is still eleven
 * characters, a masked phone is still ten digits.
 */
const hash = (s) => [...s].reduce((a, c) => (a * 31 + c.charCodeAt(0)) >>> 0, 7)

const maskValue = (column, value, rowKey) => {
  if (value == null) return null
  const name = column.toLowerCase()

  /**
   * ⚠ EMAIL IS SEEDED ON THE ROW ALONE, NOT ON THE ROW AND COLUMN.
   *
   * `users` carries `email`, `normalized_email` and `digest_email`, and a per-column seed gives all
   * three DIFFERENT masked addresses -- so `normalized_email` stops being the normalised form of
   * `email`, which is the invariant every lookup in lib/credential-match.ts depends on. One address
   * per row, lowercased where the column is the normalised one, keeps the relationship true.
   *
   * It also matters for a constraint: `idx_users_normalized_email_unique` is GLOBAL, not
   * tenant-scoped -- the only non-tenant-scoped unique index among the copied tables. The row key is
   * a uuid, so the digits below are effectively unique per row rather than merely probably unique.
   */
  if (/email/.test(name)) {
    const address = `masked-${String(hash(rowKey)).padStart(10, "0").slice(-10)}@example.invalid`
    return /normalized/.test(name) ? address.toLowerCase() : address
  }

  const seed = hash(`${rowKey}:${column}`)
  const digits = (n) => String(seed).padStart(n, "0").slice(-n)
  if (/ifsc/.test(name)) return `MASK0${digits(6)}`
  if (/phone|mobile/.test(name)) return `9${digits(9)}`
  if (/bank_account/.test(name)) return `000${digits(11)}`
  if (/bank_name/.test(name)) return "Masked Bank"
  if (/ip_address/.test(name)) return "203.0.113.1"
  if (/token_hash/.test(name)) return `masked-${digits(10)}`
  if (/address/.test(name)) return "Masked address"
  return `masked-${digits(8)}`
}

const chunk = (list, size) => {
  const out = []
  for (let i = 0; i < list.length; i += size) out.push(list.slice(i, i + size))
  return out
}

console.log(`\n=== copy "${target}": production -> dev ${commit ? "(WRITING)" : "(dry run)"} ===\n`)

// ---------------------------------------------------------------------------
// 1 · The table partition must be total. This is the #106 lesson.
// ---------------------------------------------------------------------------
//
// PR #106 fixed a guard that "knew about 40 tenant tables and the database has 53". A copy script
// with a hand-kept list has the same failure in a worse place: a table added next month is silently
// not copied, and the dev tenant is quietly missing data nobody notices is missing. So the COPY and
// EXCLUDE lists are checked to partition the live schema EXACTLY, and the script refuses to run if
// a table belongs to neither -- which forces a decision rather than a silent omission.
const liveTables = await tenantTablesOf(dev)
const known = new Set([...COPY, ...Object.keys(EXCLUDE)])
const unclassified = liveTables.filter((t) => !known.has(t))
const stale = [...known].filter((t) => !liveTables.includes(t))

if (unclassified.length) {
  console.error("REFUSING TO RUN. These tenant tables are in neither COPY nor EXCLUDE:")
  for (const t of unclassified) console.error(`  ${t}`)
  console.error("\nAdd each one to COPY (in FK order) or to EXCLUDE with a reason.")
  process.exit(1)
}
if (stale.length) {
  console.error("REFUSING TO RUN. These are listed but no longer exist in the schema:")
  for (const t of stale) console.error(`  ${t}`)
  console.error("\nRemove them, so the list stops describing a database that is gone.")
  process.exit(1)
}
console.log(`table partition: ${COPY.length} copied + ${Object.keys(EXCLUDE).length} excluded = ${liveTables.length} tenant tables ✓`)

// ---------------------------------------------------------------------------
// 2 · Resolve the tenant on prod
// ---------------------------------------------------------------------------
const found = rows(
  await prod.query(`SELECT id, name FROM tenants WHERE id::text = $1 OR name = $1`, [target]),
)
if (found.length !== 1) {
  console.error(
    found.length === 0
      ? `No production tenant matches "${target}".`
      : `"${target}" matches ${found.length} production tenants. Use the id.`,
  )
  const all = rows(await prod.query(`SELECT name FROM tenants ORDER BY name`))
  console.error(`Production tenants: ${all.map((t) => t.name).join(", ")}`)
  process.exit(1)
}
const tenant = found[0]
console.log(`resolved: ${tenant.name} (${tenant.id})\n`)

// ---------------------------------------------------------------------------
// 3 · Work out what will be masked, and SAY SO before writing anything
// ---------------------------------------------------------------------------
const plan = []
const maskPlan = []
for (const table of COPY) {
  const cols = await columnsOf(dev, table)
  if (!cols.length) {
    console.error(`REFUSING TO RUN. ${table} is in COPY but has no columns on dev.`)
    process.exit(1)
  }
  const prodCols = (await columnsOf(prod, table)).map((c) => c.column_name)
  // Only columns both sides have. Dev is ahead of prod on some migrations, and selecting a
  // dev-only column from prod is an error rather than a null.
  const shared = cols.filter((c) => prodCols.includes(c.column_name))
  const [{ n }] = rows(
    await prod.query(`SELECT COUNT(*) AS n FROM "${table}" WHERE tenant_id = $1`, [tenant.id]),
  )
  const masked = shared.filter(
    (c) => PII_NAME.test(c.column_name) && MASKABLE_TYPES.has(c.data_type),
  )
  const credentials = shared.filter((c) => CREDENTIAL_NAME.test(c.column_name))
  plan.push({ table, cols: shared, count: Number(n), masked, credentials })
  for (const c of masked) maskPlan.push(`${table}.${c.column_name}`)
  for (const c of credentials) maskPlan.push(`${table}.${c.column_name} (replaced, not masked)`)
}

console.log("PERSONAL DATA THAT WILL NOT CROSS:")
if (!maskPlan.length) console.log("  (none found — check the PII_NAME pattern still matches the schema)")
for (const m of maskPlan) console.log(`  ${m}`)

console.log("\nROWS TO COPY:")
let total = 0
for (const p of plan) {
  if (!p.count) continue
  total += p.count
  const flags = [p.masked.length ? `${p.masked.length} masked col` : null, p.credentials.length ? "credential replaced" : null]
    .filter(Boolean)
    .join(", ")
  console.log(`  ${p.table.padEnd(30)} ${String(p.count).padStart(6)}${flags ? `   (${flags})` : ""}`)
}
console.log(`  ${"".padEnd(30)} ${String(total).padStart(6)} total`)

const devExisting = rows(await dev.query(`SELECT name FROM tenants WHERE id = $1`, [tenant.id]))
console.log(
  `\ndev already has this tenant id: ${devExisting.length ? `yes ("${devExisting[0].name}") — its rows in the copied tables will be DELETED and replaced` : "no — it will be created"}`,
)

if (!commit) {
  console.log("\nDry run. Nothing was written. Re-run with --commit to apply.\n")
  process.exit(0)
}

// ---------------------------------------------------------------------------
// 4 · Write, in FK order, deleting in reverse first
// ---------------------------------------------------------------------------
console.log("\n--- writing to dev ---")

for (const table of [...COPY].reverse()) {
  const deleted = rows(
    await dev.query(`DELETE FROM "${table}" WHERE tenant_id = $1 RETURNING 1`, [tenant.id]),
  ).length
  if (deleted) console.log(`  cleared ${table}: ${deleted}`)
}

// The tenants row itself, upserted so a re-run is idempotent.
const tenantCols = (await columnsOf(dev, "tenants")).map((c) => c.column_name)
const prodTenantCols = (await columnsOf(prod, "tenants")).map((c) => c.column_name)
const tShared = tenantCols.filter((c) => prodTenantCols.includes(c))
const [tRow] = rows(
  await prod.query(`SELECT ${tShared.map((c) => `"${c}"`).join(", ")} FROM tenants WHERE id = $1`, [
    tenant.id,
  ]),
)
const tValues = tShared.map((c) => tRow[c])
const tSet = tShared.filter((c) => c !== "id").map((c, i) => `"${c}" = EXCLUDED."${c}"`)
await dev.query(
  `INSERT INTO tenants (${tShared.map((c) => `"${c}"`).join(", ")})
   VALUES (${tShared.map((_, i) => `$${i + 1}`).join(", ")})
   ON CONFLICT (id) DO UPDATE SET ${tSet.join(", ")}`,
  tValues,
)
console.log(`  tenants: upserted ${tenant.name}`)

let written = 0
/** Rows production holds that dev's current triggers refuse. Reported, never silently dropped. */
const refusals = []
for (const p of plan) {
  if (!p.count) continue
  const regenerate = REGENERATE_ID.has(p.table)
  const cols = p.cols.filter((c) => !(regenerate && c.column_name === "id"))
  const names = cols.map((c) => c.column_name)
  const typeOf = Object.fromEntries(cols.map((c) => [c.column_name, c.data_type]))
  const maskedNames = new Set(p.masked.map((c) => c.column_name))
  const credentialNames = new Set(p.credentials.map((c) => c.column_name))

  const source = rows(
    await prod.query(
      `SELECT ${names.map((n) => `"${n}"`).join(", ")} FROM "${p.table}" WHERE tenant_id = $1`,
      [tenant.id],
    ),
  )

  const colList = names.map((n) => `"${n}"`).join(", ")
  const bind = (row) => {
    // A stable per-row seed so masking is deterministic across runs.
    const rowKey = String(row.id ?? row.uuid ?? row.worker_id ?? JSON.stringify(row).slice(0, 48))
    return names.map((n) => {
      let value = row[n]
      if (credentialNames.has(n)) value = `dev-copy-not-a-real-credential-${rowKey.slice(0, 8)}`
      else if (maskedNames.has(n)) value = maskValue(n, value, rowKey)
      return encode(value, typeOf[n])
    })
  }

  let inserted = 0
  for (const batch of chunk(source, 200)) {
    const params = []
    const tuples = batch.map((row) => {
      const values = bind(row)
      const placeholders = values.map((v) => {
        params.push(v)
        return `$${params.length}`
      })
      return `(${placeholders.join(", ")})`
    })
    try {
      await dev.query(`INSERT INTO "${p.table}" (${colList}) VALUES ${tuples.join(", ")}`, params)
      inserted += batch.length
    } catch (error) {
      /**
       * ⚠ A BATCH IS ALL-OR-NOTHING, AND SOME PRODUCTION ROWS A TRIGGER NOW REFUSES ARE REAL.
       *
       * scripts/152 installed `assert_worker_day_budget` -- a worker's day is one day, shared
       * across picking and day-work. It was applied to prod on 2026-10-09, AFTER the rows it would
       * refuse already existed, and a trigger only fires on write: so prod legitimately holds
       * worker-days over the cap. STATUS.md counts 16 of them (Medappa 7, Seshagiri 9, all between
       * 27 and 31 August) and records that writers are correcting them by hand, with the red
       * "2 days" badge on the row being how they find them.
       *
       * THE REFUSAL IS NOT DROPPED SILENTLY, AND THE TRIGGER IS NOT DISABLED. Turning the guard off
       * for the duration would copy prod faithfully and risk leaving dev's muster unguarded if this
       * script died mid-run -- and `session_replication_role = replica` would switch off foreign-key
       * checks at the same time, so a genuinely broken copy would land looking fine. Instead the
       * batch is retried row by row and every refusal is reported, so the dev copy differs from
       * prod by a known, named set rather than an unknown one.
       */
      for (const row of batch) {
        try {
          const values = bind(row)
          await dev.query(
            `INSERT INTO "${p.table}" (${colList}) VALUES (${values.map((_, i) => `$${i + 1}`).join(", ")})`,
            values,
          )
          inserted += 1
        } catch (rowError) {
          refusals.push({
            table: p.table,
            /**
             * IDS ONLY — no date columns.
             *
             * This read `[row.work_date, ...]`, and the driver hands back a JS `Date` for a DATE
             * column, so `String(...)` rendered "Fri Aug 28 2026 00:00:00 GMT+0200 (Central
             * European Summer Time)" -- the runner's zone, with a human zone name appended. That is
             * signature 1 of the bug class CLAUDE.md's date section opens with, written into a
             * diagnostic whose whole job is to say which row was refused.
             *
             * Nothing here needs a date: ids are uuids, they have no timezone, and the trigger's own
             * message already names the date it refused. `scripts/dev/*.mjs` is outside
             * tests/today-is-the-estates-today.test.ts, which scans `app components lib hooks` for
             * `.ts`/`.tsx` only -- so no guard would have caught this.
             */
            key: [row.id, row.worker_id].filter(Boolean).join(" / "),
            reason: String(rowError?.message || rowError).split("\n")[0].slice(0, 200),
          })
        }
      }
    }
  }
  written += inserted
  const short = inserted === source.length ? "" : `  ⚠ ${source.length - inserted} refused`
  console.log(`  ${p.table}: ${inserted}${regenerate ? " (ids regenerated)" : ""}${short}`)
}

// ---------------------------------------------------------------------------
// 5 · Prove it landed, rather than trusting the inserts
// ---------------------------------------------------------------------------
console.log("\n--- verifying ---")
const refusedBy = new Map()
for (const r of refusals) refusedBy.set(r.table, (refusedBy.get(r.table) ?? 0) + 1)

let mismatches = 0
for (const p of plan) {
  const [{ n }] = rows(
    await dev.query(`SELECT COUNT(*) AS n FROM "${p.table}" WHERE tenant_id = $1`, [tenant.id]),
  )
  const expected = p.count - (refusedBy.get(p.table) ?? 0)
  if (Number(n) !== expected) {
    console.error(`  ✗ ${p.table}: prod ${p.count}, dev ${n}, expected ${expected}`)
    mismatches++
  }
}
console.log(
  mismatches
    ? `\n${mismatches} table(s) disagree with prod by more than the refusals below.`
    : "\nevery copied table matches prod, allowing for the refusals below ✓",
)

if (refusals.length) {
  console.log(`\n--- ${refusals.length} row(s) production holds that dev's triggers refuse ---`)
  console.log("These are real production rows. dev differs from prod by exactly this set.")
  const byReason = new Map()
  for (const r of refusals) {
    const k = `${r.table}: ${r.reason}`
    if (!byReason.has(k)) byReason.set(k, [])
    byReason.get(k).push(r.key)
  }
  for (const [reason, keys] of byReason) {
    console.log(`\n  ${reason}`)
    for (const k of keys) console.log(`    ${k}`)
  }
}

/**
 * The guard must still be on. If a future version of this script ever disables a trigger to get a
 * faithful copy, this is what catches it having failed to put it back.
 */
const triggers = rows(
  await dev.query(
    `SELECT c.relname AS table_name, t.tgname, t.tgenabled
       FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
      WHERE NOT t.tgisinternal AND t.tgenabled <> 'O'`,
  ),
)
if (triggers.length) {
  console.error("\n⚠ DISABLED TRIGGERS ON DEV — the muster guards are not enforcing:")
  for (const t of triggers) console.error(`  ${t.table_name}.${t.tgname} = ${t.tgenabled}`)
  process.exitCode = 1
} else {
  console.log("\nall dev triggers still enabled ✓")
}

/**
 * And prove the personal data did NOT cross, because that is the claim this script's existence
 * rests on and "I wrote a masking function" is not evidence that it ran.
 *
 * The check is a set intersection: pull the distinct real values from prod and the distinct values
 * now in dev, and assert the two sets do not meet. Counting masked rows would pass while leaking,
 * because a masked value is also non-null.
 */
let leaks = 0
for (const p of plan) {
  if (!p.count) continue
  for (const c of [...p.masked, ...p.credentials]) {
    const col = c.column_name
    const realValues = new Set(
      rows(
        await prod.query(
          `SELECT DISTINCT "${col}" AS v FROM "${p.table}" WHERE tenant_id = $1 AND "${col}" IS NOT NULL`,
          [tenant.id],
        ),
      ).map((r) => String(r.v)),
    )
    if (!realValues.size) continue
    const devValues = rows(
      await dev.query(
        `SELECT DISTINCT "${col}" AS v FROM "${p.table}" WHERE tenant_id = $1 AND "${col}" IS NOT NULL`,
        [tenant.id],
      ),
    ).map((r) => String(r.v))
    const crossed = devValues.filter((v) => realValues.has(v))
    if (crossed.length) {
      // The leaked VALUE is never printed -- that would put it in a terminal scrollback and a log.
      console.error(`  ✗ LEAK ${p.table}.${col}: ${crossed.length} real value(s) reached dev`)
      leaks++
    } else {
      console.log(`  ✓ ${p.table}.${col}: ${realValues.size} real value(s) in prod, 0 in dev`)
    }
  }
}
if (leaks) {
  console.error(`\n⚠ ${leaks} column(s) carried real personal data into dev. Masking did not hold.`)
  process.exitCode = 1
}

console.log(`\ndone: ${written} rows across ${plan.filter((p) => p.count).length} tables.\n`)
