/**
 * Copy ONE real tenant's operational data from production into dev, without its personal data.
 *
 * Run: node --env-file=.env.local scripts/dev/copy-tenant-from-prod.mjs "Medappa Estates"
 *      node --env-file=.env.local scripts/dev/copy-tenant-from-prod.mjs "Medappa Estates" --commit
 *
 * Needs PROD_URL exported (prod's DATABASE_URL, from .env.vercel.production -- migrate.mjs only
 * auto-loads .env/.env.local, and so does `--env-file`, so prod never arrives by accident).
 *
 * WHY THIS EXISTS, AND WHY IT IS NOT A FULL MIRROR. Dev is not a stale copy of prod; measured
 * 2026-10-19, 21 of 52 shared tenant tables matched exactly and the whole crop chain was identical
 * (HoneyFarm sales 17/17, dispatch 18/18, other sales 2/2). What dev has that prod CANNOT have is
 * the only test data for the work that matters this season: 1,150 picking_records against prod's
 * zero, plus worker_pay_rules and worker_ledger rows for a payroll depth no real estate has ever
 * exercised. A mirror would delete all of it to make dev "more realistic" and leave the harvest
 * chain with nothing to test against.
 *
 * So this copies one named tenant and touches nothing else. It generalises
 * refresh-laxmi-from-prod.mjs, which hardcoded Laxmi, cleared the muster tables (right for a
 * pre-cutover rehearsal, wrong for an already-cut-over tenant) and copied twelve tables out of
 * fifty-three.
 *
 * ⚠ PRODUCTION IS ONLY EVER READ. Every write targets DATABASE_URL_DEV, and the script refuses to
 * run if the two connection strings are the same database.
 *
 * ⚠ PERSONAL DATA IS NOT COPIED, AND THE COLUMN LIST IS DERIVED RATHER THAN REMEMBERED.
 * `DATABASE_URL_DEV` has been a GitHub Actions secret since 2026-10-14, so dev is a database CI
 * connects to -- carrying 43 real workers' bank accounts and IFSC codes into it would put live
 * financial PII somewhere with weaker access rules, to no testing benefit whatsoever. Columns are
 * matched by NAME PATTERN against the live schema, so a `bank_account` added to a new table
 * tomorrow is masked tomorrow. Deriving it also found two columns a hand-written list would have
 * missed: `sales_records.bank_account` and `other_sales_records.bank_account` -- bank details live
 * on sales rows, not only on workers.
 */
import { neon } from "@neondatabase/serverless"

const commit = process.argv.includes("--commit")
const target = process.argv.slice(2).find((a) => !a.startsWith("--"))

if (!target) {
  console.error('Usage: copy-tenant-from-prod.mjs "<tenant name or id>" [--commit]')
  process.exit(1)
}
if (!process.env.PROD_URL) {
  console.error("PROD_URL is not set. Export prod's DATABASE_URL from .env.vercel.production first.")
  process.exit(1)
}
if (!process.env.DATABASE_URL_DEV) {
  console.error("DATABASE_URL_DEV is not set. Run with --env-file=.env.local.")
  process.exit(1)
}
// The whole safety story here is "prod is read-only". That holds only if these are two databases.
if (process.env.PROD_URL === process.env.DATABASE_URL_DEV) {
  console.error("PROD_URL and DATABASE_URL_DEV are the same database. Refusing to run.")
  process.exit(1)
}

const prod = neon(process.env.PROD_URL)
const dev = neon(process.env.DATABASE_URL_DEV)
const rows = (r) => (Array.isArray(r) ? r : r?.rows ?? [])

